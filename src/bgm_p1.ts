// ===== P1 の BGM（オリジナル曲）「神々の塔」第一楽章〜第三楽章 =====
// ユーザーが妖星乱舞（第一〜第三楽章）の雰囲気・テンポ・調・和音の進み方を分析して作ったプロンプトから作曲（2026-10-15）
// 旋律・和音の並び・リズムはすべてオリジナル（原曲のメロディーは使わない）。3つで「塔を下から上へ登る」流れ
//   第一楽章（足元）：嬰ハ短調・とても遅い（58）。低音が居座る中、高い音を長く伸ばし、内声が半音で揺れる。オルガンと合唱の儀式
//   第二楽章（中腹）：ハ短調とハ長調が入れ替わる・130。低音は半音を行き来する刻み。上は跳ねる分散和音、ブラスの旋律
//   第三楽章（頂上）：嬰ハ長調・172。主和音の速い分散和音に居座ってから、曇って、どんどん転調して上る
// 1小節＝16分音符×16。打楽器はティンパニとシンバルだけ（原曲も打楽器が少ない）

// [音, 長さ] の列を順に置く。null は休み
const line = (add, s0, notes, ch) => { let s = s0; notes.forEach(([n, l]) => { if (n) add(s, ch, n, l); s += l; }); };
const hold = (add, s0, notes, l, ch) => notes.forEach(n => add(s0, ch, n, l));

// ---------- 第一楽章：塔の足元 ----------
const BPM1 = 58;
function p1First(api){
  const { add, bar, pos } = api;
  // イントロ（最初だけ）：低い保続音と鐘、ティンパニが近づいてくる
  bar(16, BPM1, s0 => { add(s0, 'pedal', 'C#1', 16); add(s0, 'organ2', 'C#2', 16); add(s0, 'choir2', 'G#3', 16); add(s0, 'timp', 'C#2'); add(s0 + 8, 'timp', 'C#2'); add(s0, 'bell', 'C#5'); });
  bar(16, BPM1, s0 => {
    add(s0, 'pedal', 'C#1', 16); hold(add, s0, ['C#2', 'G#2', 'C#3'], 16, 'organ2'); hold(add, s0, ['C#4', 'E4'], 16, 'choir2');
    for (let i = 8; i < 16; i++) add(s0 + i, 'timp', i % 2 ? 'G#1' : 'C#2');
    add(s0 + 12, 'bell', 'G#4');
  });
  const LOOP = pos();
  // c：オルガンの和音、p：ペダル、top：高い声（合唱）、inner：内声（弦。半音で揺れる）
  const BARS = [
    { c:['C#3', 'G#3', 'C#4', 'E4'], p:'C#1', top:[['E5', 16]], inner:[['C#4', 4], ['D4', 4], ['C#4', 4], ['B#3', 4]], bell:'C#6' },
    { c:['C#3', 'G#3', 'C#4', 'E4'], p:'C#1', top:[['E5', 8], ['F#5', 4], ['E5', 4]], inner:[['C#4', 4], ['D4', 4], ['C#4', 4], ['B#3', 4]] },
    { c:['A2', 'E3', 'A3', 'C#4'], p:'A1', top:[['C#5', 8], ['D5', 4], ['C#5', 4]], inner:[['A3', 8], ['G#3', 8]] },
    { c:['G#2', 'D#3', 'G#3', 'B#3'], p:'G#1', top:[['B#4', 8], ['D#5', 8]], inner:[['F#3', 8], ['G#3', 8]], roll:true },
    // 平行調（ホ長調）に一瞬だけ明るく開く
    { c:['E3', 'B3', 'E4', 'G#4'], p:'E1', top:[['G#5', 8], ['B5', 8]], inner:[['B3', 16]], bell:'E6' },
    { c:['B2', 'F#3', 'B3', 'D#4'], p:'B1', top:[['A5', 4], ['G#5', 4], ['F#5', 8]], inner:[['D#4', 8], ['E4', 8]] },
    // ニ長調（嬰ハから見て半音上）で暗く揺らしてから、属七（G#7）で足元へ戻る
    { c:['D3', 'A3', 'D4', 'F#4'], p:'D1', top:[['F#5', 8], ['E5', 4], ['D5', 4]], inner:[['A3', 8], ['G#3', 8]] },
    { c:['G#2', 'B#2', 'D#3', 'F#3'], p:'G#1', top:[['D#5', 8], ['B#4', 8]], inner:[['F#3', 4], ['E#3', 4], ['F#3', 4], ['G#3', 4]], roll:true },
  ];
  BARS.forEach(b => bar(16, BPM1, s0 => {
    hold(add, s0, b.c, 16, 'organ2'); add(s0, 'pedal', b.p, 16);
    line(add, s0, b.top, 'choir2'); line(add, s0, b.top.map(([n, l]) => [n.replace(/\d/, d => String(+d - 1)), l]), 'str');
    line(add, s0, b.inner, 'str');
    add(s0, 'timp', b.p.replace(/\d/, '2'));
    if (b.bell) add(s0, 'bell', b.bell);
    if (b.roll) for (let i = 10; i < 16; i++) add(s0 + i, 'timp', b.p.replace(/\d/, '2'));
  }));
  return LOOP;
}

// ---------- 第二楽章：塔の中腹 ----------
const BPM2 = 130;
function p1Second(api){
  const { add, bar, pos } = api;
  // 低音：8分音符で根音と半音上を行き来する刻み（不安をあおる）
  const osc = (s0, a, b) => { for (let i = 0; i < 16; i += 2) add(s0 + i, 'bass', i % 4 ? b : a, 2); };
  // 上：和音の音を跳ねて回る16分（ハープより硬いトッカータの音色）
  const FIG = [0, 2, 1, 3, 2, 1, 3, 2, 0, 3, 1, 2, 3, 1, 2, 0];
  const fig = (s0, ch) => FIG.forEach((k, i) => add(s0 + i, 'toc', ch[k], 1));
  // イントロ（最初だけ）：刻みとティンパニだけ
  bar(16, BPM2, s0 => { osc(s0, 'C2', 'Db2'); add(s0, 'timp', 'C2'); add(s0 + 8, 'timp', 'G1'); });
  bar(16, BPM2, s0 => { osc(s0, 'C2', 'Db2'); add(s0, 'timp', 'C2'); add(s0 + 8, 'timp', 'G1'); hold(add, s0, ['C4', 'G4'], 16, 'choir2'); for (let i = 12; i < 16; i++) add(s0 + i, 'timp', 'C2'); });
  const LOOP = pos();
  // A：ハ短調とハ長調が1小節ごとに入れ替わる。B：変ホ長調に明るく出て、ニ短調・ニ長調を通ってト（属和音）へ
  const BARS = [
    { c:['C4', 'Eb4', 'G4', 'C5'], o:['C2', 'Db2'], m:[['G4', 6], ['Ab4', 2], ['G4', 4], ['Eb5', 4]], crash:true },
    { c:['C4', 'E4', 'G4', 'C5'], o:['C2', 'Db2'], m:[['E5', 6], ['D5', 2], ['C5', 4], ['G4', 4]] },
    { c:['C4', 'Eb4', 'G4', 'C5'], o:['C2', 'Db2'], m:[['Ab4', 4], ['G4', 4], ['Eb4', 4], ['F4', 2], ['G4', 2]] },
    { c:['C4', 'E4', 'G4', 'C5'], o:['C2', 'Db2'], m:[['C5', 12], ['B4', 4]] },
    { c:['C4', 'F4', 'Ab4', 'C5'], o:['F1', 'Gb1'], m:[['C5', 4], ['Db5', 4], ['F5', 6], ['Eb5', 2]] },
    { c:['C4', 'Eb4', 'G4', 'C5'], o:['C2', 'Db2'], m:[['D5', 4], ['Eb5', 4], ['G5', 8]] },
    { c:['Db4', 'F4', 'Ab4', 'Db5'], o:['Db2', 'D2'], m:[['Ab5', 6], ['F5', 2], ['Db5', 4], ['C5', 4]] },
    { c:['B3', 'D4', 'F4', 'G4'], o:['G1', 'Ab1'], m:[['B4', 8], ['D5', 4], ['F5', 4]] },
    { c:['Eb4', 'G4', 'Bb4', 'Eb5'], o:['Eb2', 'E2'], m:[['G5', 8], ['Bb5', 8]], crash:true },
    { c:['D4', 'F4', 'Bb4', 'D5'], o:['Bb1', 'B1'], m:[['F5', 8], ['D5', 8]] },
    { c:['C4', 'Eb4', 'Ab4', 'C5'], o:['Ab1', 'A1'], m:[['Eb5', 6], ['C5', 2], ['Ab4', 8]] },
    { c:['B3', 'D4', 'G4', 'B4'], o:['G1', 'Ab1'], m:[['B4', 4], ['D5', 4], ['G5', 8]] },
    { c:['Eb4', 'G4', 'Bb4', 'Eb5'], o:['Eb2', 'E2'], m:[['G5', 4], ['Ab5', 4], ['Bb5', 8]] },
    { c:['D4', 'F4', 'A4', 'D5'], o:['D2', 'Eb2'], m:[['A5', 8], ['F5', 8]] },
    { c:['D4', 'F#4', 'A4', 'D5'], o:['D2', 'Eb2'], m:[['F#5', 8], ['A5', 8]] },
    { c:['B3', 'D4', 'F4', 'G4'], o:['G1', 'Ab1'], m:[['G5', 4], ['F5', 4], ['D5', 4], ['B4', 4]], roll:true },
  ];
  BARS.forEach(b => bar(16, BPM2, s0 => {
    osc(s0, b.o[0], b.o[1]); fig(s0, b.c);
    hold(add, s0, b.c.slice(0, 3), 16, 'choir2'); hold(add, s0, b.c.slice(0, 3), 16, 'str');
    line(add, s0, b.m, 'brass');
    add(s0, 'timp', b.o[0].replace(/\d/, '2')); add(s0 + 8, 'timp', b.o[0].replace(/\d/, '2'));
    if (b.crash) add(s0, 'crash');
    if (b.roll) for (let i = 12; i < 16; i++) add(s0 + i, 'timp', 'G1');
  }));
  return LOOP;
}

// ---------- 第三楽章：塔の頂上 ----------
const BPM3 = 172;
function p1Third(api){
  const { add, bar, pos } = api;
  // 主和音の速い分散和音（16分）。上って下りる形をずらしながら繰り返す
  const ARP = [0, 2, 1, 2, 3, 2, 1, 2, 0, 1, 2, 3, 2, 3, 1, 2];
  const arp = (s0, ch) => ARP.forEach((k, i) => add(s0 + i, 'toc', ch[k], 1));
  // イントロ（最初だけ）：分散和音と保続音だけで、頂上が見えてくる
  [0, 1].forEach(k => bar(16, BPM3, s0 => { arp(s0, ['C#4', 'E#4', 'G#4', 'C#5']); add(s0, 'pedal', 'C#1', 16); if (k === 0) add(s0, 'timp', 'C#2'); else for (let i = 8; i < 16; i += 2) add(s0 + i, 'timp', 'C#2'); }));
  const LOOP = pos();
  const BARS = [
    // A：嬰ハ長調に居座る（保続音 C#）。合唱が高く伸びる旋律
    { a:['C#4', 'E#4', 'G#4', 'C#5'], c:['C#3', 'G#3', 'C#4', 'E#4'], p:'C#1', m:[['E#5', 8], ['G#5', 8]], crash:true, bell:'C#6' },
    { a:['C#4', 'E#4', 'G#4', 'C#5'], c:['C#3', 'G#3', 'C#4', 'E#4'], p:'C#1', m:[['C#6', 12], ['A#5', 4]] },
    { a:['C#4', 'F#4', 'A#4', 'C#5'], c:['C#3', 'F#3', 'A#3', 'C#4'], p:'C#1', m:[['A#5', 8], ['G#5', 4], ['F#5', 4]] },
    { a:['C#4', 'E#4', 'G#4', 'C#5'], c:['C#3', 'G#3', 'C#4', 'E#4'], p:'C#1', m:[['G#5', 16]] },
    { a:['B#3', 'D#4', 'G#4', 'B#4'], c:['G#2', 'D#3', 'G#3', 'B#3'], p:'C#1', m:[['B#5', 8], ['D#6', 8]], bell:'G#5' },
    { a:['C#4', 'E#4', 'G#4', 'C#5'], c:['C#3', 'G#3', 'C#4', 'E#4'], p:'C#1', m:[['C#6', 8], ['G#5', 8]] },
    { a:['C#4', 'F#4', 'A#4', 'C#5'], c:['F#2', 'C#3', 'F#3', 'A#3'], p:'C#1', m:[['E#5', 4], ['G#5', 4], ['A#5', 4], ['B#5', 4]] },
    { a:['C#4', 'E#4', 'G#4', 'C#5'], c:['C#3', 'G#3', 'C#4', 'E#4'], p:'C#1', m:[['C#6', 16]], bell:'C#6' },
    // B：嬰ハ短調に曇る
    { a:['C#4', 'E4', 'G#4', 'C#5'], c:['C#3', 'G#3', 'C#4', 'E4'], p:'C#1', m:[['E5', 8], ['D#5', 8]], crash:true },
    { a:['C#4', 'E4', 'G#4', 'C#5'], c:['C#3', 'G#3', 'C#4', 'E4'], p:'C#1', m:[['C#5', 16]] },
    // C：どんどん転調して上る（イ短調 → ニ長調 → ト長調 → 嬰ト七で頂上へ戻る）
    { a:['A3', 'C4', 'E4', 'A4'], c:['A2', 'E3', 'A3', 'C4'], p:'A1', m:[['E5', 8], ['A5', 8]], crash:true },
    { a:['A3', 'C4', 'E4', 'A4'], c:['A2', 'E3', 'A3', 'C4'], p:'A1', m:[['C6', 12], ['B5', 4]] },
    { a:['D4', 'F#4', 'A4', 'D5'], c:['D3', 'A3', 'D4', 'F#4'], p:'D1', m:[['A5', 8], ['F#5', 8]], crash:true },
    { a:['D4', 'F#4', 'A4', 'D5'], c:['D3', 'A3', 'D4', 'F#4'], p:'D1', m:[['D6', 16]] },
    { a:['G4', 'B4', 'D5', 'G5'], c:['G2', 'D3', 'G3', 'B3'], p:'G1', m:[['B5', 8], ['D6', 8]], crash:true, bell:'G6' },
    { a:['G#4', 'B#4', 'D#5', 'F#5'], c:['G#2', 'D#3', 'F#3', 'B#3'], p:'G#1', m:[['B#5', 4], ['D#6', 4], ['F#6', 4], ['G#6', 4]], roll:true },
  ];
  BARS.forEach(b => bar(16, BPM3, s0 => {
    arp(s0, b.a); hold(add, s0, b.c, 16, 'organ2'); add(s0, 'pedal', b.p, 16);
    line(add, s0, b.m, 'choir2'); line(add, s0, b.m, 'str');
    add(s0, 'timp', b.p.replace(/\d/, '2'));
    if (b.crash) add(s0, 'crash');
    if (b.bell) add(s0, 'bell', b.bell);
    if (b.roll) for (let i = 8; i < 16; i += 2) add(s0 + i, 'timp', 'G#1');
  }));
  return LOOP;
}

