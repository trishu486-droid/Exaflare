// ===== 追加の BGM（オリジナル曲）2曲 =====
// ユーザーが送ってくれた2つの録音の雰囲気・テンポ・調・和音の進み方・低音の動きを分析して作曲（2026-10-15）
// 旋律・和音の並び・リズムはすべてオリジナル（原曲のメロディーは使わない）
//   堕ちる星：イ短調・136。低音がよく動き（歩くように上下・半音で上る）、低い音が厚い。明るい長調の和音へ何度も寄り道する
//   魔導の祭壇：嬰ハ短調・103。ホの保続音と高い音の前奏 → 暗いヘの保続音 → オルガンが低い所でうねる本編。途中で半音ずれた暗い調へ
// 打楽器は少なめ（録音も2つとも打楽器は1割くらい）

const line = (add, s0, notes, ch) => { let s = s0; notes.forEach(([n, l]) => { if (n) add(s, ch, n, l); s += l; }); };
const hold = (add, s0, notes, l, ch) => notes.forEach(n => add(s0, ch, n, l));
const oct = (n, k) => n.replace(/\d/, d => String(+d + k));

// ---------- 堕ちる星（イ短調・136） ----------
const BPM_A = 136;
function fallingStar(api){
  const { add, bar, pos } = api;
  // 低音：1拍ごとの音を8分で2回ずつ（下の音はペダルで太く）
  const walk = (s0, b) => b.forEach((n, i) => { add(s0 + i * 4, 'bass', n, 2); add(s0 + i * 4 + 2, 'bass', oct(n, 1), 2); });
  // 和音の8分の分散（ハープ）
  const harp = (s0, c) => [0, 1, 2, 3, 2, 1, 2, 3].forEach((k, i) => add(s0 + i * 2, 'harp', c[k], 2));
  // 打楽器は軽く：1・3拍目にバスドラ、2・4拍目にハイハット
  const beat = s0 => { add(s0, 'kick'); add(s0 + 8, 'kick'); add(s0 + 4, 'hat'); add(s0 + 12, 'hat'); };
  bar(16, BPM_A, s0 => { walk(s0, ['A1', 'A1', 'E2', 'G#1']); add(s0, 'timp', 'A2'); add(s0 + 8, 'timp', 'E2'); for (let i = 12; i < 16; i++) add(s0 + i, 'timp', 'A2'); });
  const LOOP = pos();
  // c：和音（ハープ・オルガン）、b：低音（4拍）、m：旋律
  const BARS = [
    // A：イ短調。ホ長調とイ長調に明るく寄り道する
    { c:['A3', 'C4', 'E4', 'A4'], b:['A1', 'A2', 'G2', 'E2'], m:[['A4', 4], ['C5', 2], ['E5', 2], ['D5', 4], ['C5', 4]], crash:true },
    { c:['A3', 'C4', 'E4', 'A4'], b:['A1', 'C2', 'E2', 'G2'], m:[['B4', 2], ['C5', 2], ['D5', 4], ['E5', 8]] },
    { c:['G#3', 'B3', 'E4', 'G#4'], b:['G#1', 'B1', 'E2', 'G#2'], m:[['G#4', 4], ['B4', 4], ['E5', 6], ['D5', 2]] },
    { c:['A3', 'C4', 'E4', 'A4'], b:['A1', 'E2', 'A2', 'G2'], m:[['C5', 6], ['B4', 2], ['A4', 8]] },
    { c:['A3', 'C4', 'F4', 'A4'], b:['F1', 'C2', 'F2', 'F#2'], m:[['A4', 4], ['C5', 4], ['F5', 6], ['E5', 2]] },
    { c:['G3', 'B3', 'D4', 'G4'], b:['G1', 'D2', 'G2', 'G#2'], m:[['D5', 4], ['B4', 4], ['G4', 4], ['B4', 4]] },
    { c:['G#3', 'B3', 'D4', 'E4'], b:['E1', 'B1', 'E2', 'G#2'], m:[['E5', 4], ['F5', 2], ['E5', 2], ['D5', 4], ['B4', 4]] },
    { c:['A3', 'C#4', 'E4', 'A4'], b:['A1', 'C#2', 'E2', 'G2'], m:[['C#5', 8], ['E5', 8]], fill:true },
    // B：ニ短調から、長調の和音を渡り歩いて高く上る
    { c:['A3', 'D4', 'F4', 'A4'], b:['D2', 'A1', 'D2', 'F2'], m:[['F5', 4], ['E5', 2], ['D5', 2], ['A4', 8]], crash:true },
    { c:['G3', 'Bb3', 'D4', 'G4'], b:['G1', 'D2', 'G2', 'F2'], m:[['Bb4', 4], ['D5', 4], ['G5', 8]] },
    { c:['G3', 'C4', 'E4', 'G4'], b:['C2', 'G1', 'C2', 'E2'], m:[['E5', 4], ['G5', 4], ['C6', 6], ['Bb5', 2]] },
    { c:['G3', 'B3', 'D4', 'G4'], b:['G1', 'B1', 'D2', 'F#2'], m:[['B5', 8], ['G5', 4], ['D5', 4]] },
    { c:['F#3', 'A3', 'D4', 'F#4'], b:['D2', 'A1', 'F#2', 'A2'], m:[['F#5', 4], ['A5', 4], ['D6', 8]], crash:true },
    { c:['F3', 'A3', 'C4', 'F4'], b:['F1', 'C2', 'F2', 'E2'], m:[['C6', 4], ['A5', 4], ['F5', 4], ['A5', 4]] },
    { c:['E3', 'G3', 'C4', 'E4'], b:['C2', 'E2', 'G2', 'C2'], m:[['G5', 8], ['E5', 4], ['C5', 4]] },
    { c:['F3', 'A3', 'C4', 'F4'], b:['F1', 'F2', 'E2', 'Eb2'], m:[['A5', 12], ['G5', 4]], fill:true },
    // C：減和音とハ短調で曇らせ、ホの属七でイ短調へ戻る
    { c:['F#3', 'A3', 'C4', 'Eb4'], b:['F#1', 'A1', 'C2', 'Eb2'], m:[['A5', 4], ['C6', 4], ['Eb6', 8]], crash:true },
    { c:['G3', 'C4', 'Eb4', 'G4'], b:['C2', 'G1', 'Eb2', 'D2'], m:[['Eb6', 4], ['D6', 4], ['C6', 4], ['G5', 4]] },
    { c:['A3', 'D4', 'F4', 'A4'], b:['D2', 'F2', 'A2', 'F2'], m:[['F5', 6], ['E5', 2], ['D5', 4], ['A4', 4]] },
    { c:['G#3', 'B3', 'D4', 'E4'], b:['E1', 'G#1', 'B1', 'D2'], m:[['G#4', 4], ['B4', 4], ['D5', 4], ['E5', 4]], roll:true },
  ];
  BARS.forEach(b => bar(16, BPM_A, s0 => {
    walk(s0, b.b); add(s0, 'pedal', oct(b.b[0], -1), 16);
    harp(s0, b.c); hold(add, s0, b.c.slice(0, 3), 16, 'organ2');
    line(add, s0, b.m, 'violin'); line(add, s0, b.m.map(([n, l]) => [oct(n, -1), l]), 'sbrass2');
    beat(s0);
    if (b.crash) add(s0, 'crash');
    if (b.fill) for (let i = 12; i < 16; i++) add(s0 + i, 'timp', oct(b.b[0], 1));
    if (b.roll) for (let i = 8; i < 16; i++) add(s0 + i, 'timp', i % 2 ? 'B1' : 'E2');
  }));
  return LOOP;
}

// ---------- 魔導の祭壇（嬰ハ短調・103） ----------
const BPM_B = 103;
function altar(api){
  const { add, bar, pos } = api;
  // 左手のオルガン：根音のまわりを16分でうねる（下の隣の音・上の2音を回る）
  const turn = (s0, r, lo, a, b) => [r, lo, r, a, b, a, r, lo, r, a, b, a, r, lo, a, r].forEach((n, i) => add(s0 + i, 'organ', n, 1));
  // 前奏（最初だけ）：ホの保続音と高い E が張りつめ、そのあと暗いヘの保続音へ
  [0, 1].forEach(k => bar(16, BPM_B, s0 => {
    add(s0, 'pedal', 'E1', 16); hold(add, s0, ['E2', 'B2', 'E3'], 16, 'organ2'); add(s0, 'choir2', 'E6', 16); add(s0, 'str', 'E5', 16);
    if (k === 0) add(s0, 'bell', 'E6'); else line(add, s0, [['B4', 4], ['D5', 4], ['E5', 8]], 'str');
    add(s0, 'timp', 'E2');
  }));
  [0, 1].forEach(k => bar(16, BPM_B, s0 => {
    add(s0, 'pedal', 'F1', 16); hold(add, s0, ['F2', 'C3', 'F3', 'Ab3'], 16, 'organ2'); add(s0, 'choir2', k ? 'Db6' : 'C6', 16);
    add(s0, 'timp', 'F2'); if (k) for (let i = 8; i < 16; i++) add(s0 + i, 'timp', i % 2 ? 'C2' : 'F2');
  }));
  const LOOP = pos();
  // t：うねりの4音（根音・下の隣・上の2音）、c：上の和音（合唱）、p：ペダル、m：旋律（オルガンと弦）
  const BARS = [
    { t:['C#3', 'B#2', 'E3', 'G#3'], c:['G#4', 'C#5', 'E5'], p:'C#1', m:[['G#4', 8], ['C#5', 4], ['E5', 4]], crash:true },
    { t:['F#3', 'E#3', 'A3', 'C#4'], c:['A4', 'C#5', 'F#5'], p:'F#1', m:[['F#5', 8], ['E5', 4], ['C#5', 4]] },
    { t:['C#3', 'B#2', 'E3', 'G#3'], c:['G#4', 'C#5', 'E5'], p:'C#1', m:[['D#5', 2], ['E5', 2], ['D#5', 4], ['C#5', 8]] },
    { t:['F#3', 'E#3', 'A#3', 'C#4'], c:['A#4', 'C#5', 'F#5'], p:'F#1', m:[['A#4', 8], ['C#5', 4], ['F#5', 4]] },
    { t:['C#3', 'B#2', 'E#3', 'G#3'], c:['G#4', 'C#5', 'E#5'], p:'C#1', m:[['E#5', 12], ['C#5', 4]] },
    { t:['F#3', 'E#3', 'A3', 'C4'], c:['A4', 'C5', 'F#5'], p:'F#1', m:[['C6', 8], ['A5', 4], ['F#5', 4]] },
    { t:['C#3', 'B#2', 'E3', 'G#3'], c:['G#4', 'C#5', 'E5'], p:'C#1', m:[['G#5', 8], ['E5', 4], ['C#5', 4]] },
    { t:['E3', 'D#3', 'G#3', 'B3'], c:['G#4', 'B4', 'E5'], p:'E1', m:[['B4', 4], ['E5', 4], ['G#5', 8]], roll:true },
    // 途中：半音ずれた暗い調（ヘ短調・ハ短調）と、三全音離れた和音（嬰へ・ハ）がぶつかる
    { t:['F3', 'E3', 'Ab3', 'C4'], c:['Ab4', 'C5', 'F5'], p:'F1', m:[['Ab5', 8], ['G5', 4], ['F5', 4]], crash:true },
    { t:['C3', 'B2', 'Eb3', 'G3'], c:['G4', 'C5', 'Eb5'], p:'C1', m:[['Eb5', 8], ['G5', 8]] },
    { t:['F#3', 'E#3', 'A#3', 'C#4'], c:['A#4', 'C#5', 'F#5'], p:'F#1', m:[['A#5', 8], ['C#6', 8]] },
    { t:['C3', 'B2', 'E3', 'G3'], c:['G4', 'C5', 'E5'], p:'C1', m:[['C6', 4], ['B5', 4], ['G5', 8]], roll:true },
    // 戻り：嬰ハ短調に戻って、高い所で揺れてから属和音（嬰ト）で頭へ
    { t:['C#3', 'B#2', 'E3', 'G#3'], c:['G#4', 'C#5', 'E5'], p:'C#1', m:[['C#6', 16]], crash:true },
    { t:['C3', 'B2', 'E3', 'G3'], c:['G4', 'C5', 'E5'], p:'C1', m:[['C6', 8], ['G5', 8]] },
    { t:['D#3', 'D3', 'F#3', 'A#3'], c:['A#4', 'D#5', 'F#5'], p:'D#1', m:[['D#6', 8], ['A#5', 8]] },
    { t:['G#2', 'G2', 'B#2', 'D#3'], c:['B#4', 'D#5', 'G#5'], p:'G#1', m:[['B#5', 4], ['D#6', 4], ['G#5', 8]], roll:true },
  ];
  BARS.forEach(b => bar(16, BPM_B, s0 => {
    turn(s0, ...b.t); add(s0, 'bass', oct(b.p, 1), 16);
    hold(add, s0, b.c, 16, 'choir2');
    line(add, s0, b.m, 'organ2'); line(add, s0, b.m, 'str');
    add(s0, 'timp', oct(b.p, 1)); add(s0 + 8, 'timp', oct(b.p, 1));
    if (b.crash) add(s0, 'crash');
    if (b.roll) for (let i = 12; i < 16; i++) add(s0 + i, 'timp', oct(b.p, 1));
  }));
  return LOOP;
}

export { fallingStar, altar };
