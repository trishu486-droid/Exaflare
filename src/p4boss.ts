// 最初に使うときに小さいキャンバスへ1回だけ描いて、毎フレームはそれを貼るだけ
function mk(w, h, scale){
  const c = document.createElement('canvas'); c.width = w; c.height = h;
  c.style.width = w * scale + 'px'; c.style.height = h * scale + 'px'; c.style.imageRendering = 'pixelated';
  const g = c.getContext('2d');
  const P = {
    c, g, w, h,
    px(x, y, col){ if (x < 0 || y < 0 || x >= w || y >= h) return; g.fillStyle = col; g.fillRect(x | 0, y | 0, 1, 1); },
    rect(x, y, ww, hh, col){ g.fillStyle = col; g.fillRect(x, y, ww, hh); },
    disc(cx, cy, r, col){ for (let y = -r; y <= r; y++) for (let x = -r; x <= r; x++) if (x * x + y * y <= r * r + r * .6) P.px(cx + x, cy + y, col); },
    ell(cx, cy, rx, ry, col){ for (let y = -ry; y <= ry; y++) for (let x = -rx; x <= rx; x++) if ((x * x) / (rx * rx + .5) + (y * y) / (ry * ry + .5) <= 1) P.px(cx + x, cy + y, col); },
    ring(cx, cy, r, col){ for (let a = 0; a < 360; a += 2){ P.px(Math.round(cx + Math.cos(a * Math.PI / 180) * r), Math.round(cy + Math.sin(a * Math.PI / 180) * r), col); } },
    line(x0, y0, x1, y1, col){ x0 |= 0; y0 |= 0; x1 |= 0; y1 |= 0; const dx = Math.abs(x1 - x0), dy = -Math.abs(y1 - y0), sx = x0 < x1 ? 1 : -1, sy = y0 < y1 ? 1 : -1; let e = dx + dy; for (;;){ P.px(x0, y0, col); if (x0 === x1 && y0 === y1) break; const e2 = 2 * e; if (e2 >= dy){ e += dy; x0 += sx; } if (e2 <= dx){ e += dx; y0 += sy; } } },
    poly(pts, col){ // 塗りつぶし多角形
      const ys = pts.map(p => p[1]), y0 = Math.min(...ys), y1 = Math.max(...ys);
      for (let y = Math.floor(y0); y <= Math.ceil(y1); y++){
        const xs = [];
        for (let i = 0; i < pts.length; i++){ const [ax, ay] = pts[i], [bx, by] = pts[(i + 1) % pts.length]; if ((ay <= y + .5 && by > y + .5) || (by <= y + .5 && ay > y + .5)) xs.push(ax + (y + .5 - ay) * (bx - ax) / (by - ay)); }
        xs.sort((a, b) => a - b);
        for (let i = 0; i + 1 < xs.length; i += 2) for (let x = Math.round(xs[i]); x < Math.round(xs[i + 1]); x++) P.px(x, y, col);
      }
    },
    // 輪郭：指定色以外の塗りのまわりを縁取る
    outline(col){
      const d = g.getImageData(0, 0, w, h).data, on = (x, y) => x >= 0 && y >= 0 && x < w && y < h && d[(y * w + x) * 4 + 3] > 0;
      const out = [];
      for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) if (!on(x, y) && (on(x - 1, y) || on(x + 1, y) || on(x, y - 1) || on(x, y + 1))) out.push([x, y]);
      out.forEach(([x, y]) => P.px(x, y, col));
    },
  };
  return P;
}
